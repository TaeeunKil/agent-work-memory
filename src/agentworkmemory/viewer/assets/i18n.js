const ENGLISH_KEYS = Object.keys(MESSAGES.en).sort();
for (const locale of SUPPORTED_LOCALES) {
  const keys = Object.keys(MESSAGES[locale]).sort();
  if (keys.length !== ENGLISH_KEYS.length || keys.some((key, index) => key !== ENGLISH_KEYS[index])) {
    throw new Error(`Locale catalog ${locale} does not match the English catalog`);
  }
}

export function preferredLocale(storage = window.localStorage) {
  try {
    const stored = storage.getItem(LOCALE_STORAGE_KEY);
    if (SUPPORTED_LOCALES.includes(stored)) return stored;
  } catch {
    // The browser may deny storage; use its language for this session.
  }
  return "en";
}

export function persistLocale(locale, storage = window.localStorage) {
  if (!SUPPORTED_LOCALES.includes(locale)) throw new Error(`Unsupported locale: ${locale}`);
  try {
    storage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Language switching remains available for the current session.
  }
}

export function translate(locale, key, values = {}) {
  const template = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function pageLabel(page, locale) {
  const primary = locale === "ko" ? page.short_title_ko : page.short_title_en;
  const secondary = locale === "ko" ? page.short_title_en : page.short_title_ko;
  return primary || secondary || page.title;
}

export function localeName(locale, displayLocale) {
  return translate(displayLocale, `language.${locale}`);
}
